class TestComparison(unittest.TestCase):
    """Detect IBD from genotypes alone, with no vendor involved."""

    @classmethod
    def setUpClass(cls):
        cls.store, cls.child, cls.mother, cls.gmap, cls.path = helpers.parent_child_store()
        cls.cmp = relate_mod.compare(
            cls.store, cls.child, cls.mother, cls.gmap, min_cm=7.0, min_snps=20
        )

    @classmethod
    def tearDownClass(cls):
        helpers.cleanup(cls.store, cls.path)

    def test_parent_child_shares_whole_genome(self):
        genome = self.gmap.autosomal_total_cm()
        self.assertGreater(
            self.cmp.total_cm, genome * 0.90,
            "a parent and child are half-identical across essentially every "
            f"chromosome; got {self.cmp.total_cm:.0f} of {genome:.0f} cM",
        )

    def test_no_opposite_homozygotes(self):
        self.assertLess(
            self.cmp.ibs0_rate, 0.01,
            "opposite homozygotes are impossible between parent and child "
            "except through genotyping error",
        )

    def test_classification(self):
        verdict = relate_mod.classify_close(self.cmp, self.gmap)
        self.assertEqual(verdict.label, "parent/child")

    def test_verify_parent_gate(self):
        ok, _why = relate_mod.verify_parent(self.cmp, self.gmap)
        self.assertTrue(ok)

    def test_unrelated_pair_shares_little(self):
        store, a, b, gmap, path = helpers.unrelated_store()
        try:
            cmp = relate_mod.compare(store, a, b, gmap, min_cm=7.0, min_snps=20)
            genome = gmap.autosomal_total_cm()
            self.assertLess(
                cmp.total_cm, genome * 0.35,
                "unrelated people should not look half-identical genome-wide",
            )
            ok, _ = relate_mod.verify_parent(cmp, gmap)
            self.assertFalse(ok, "the parent gate must reject unrelated kits")
        finally:
            helpers.cleanup(store, path)


class TestPhasing(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.store, cls.child, cls.mother, cls.gmap, cls.path = helpers.parent_child_store()
        cls.stats = phase_mod.phase_against_parent(
            cls.store, cls.child, cls.mother, parent_role="mother"
        )

    @classmethod
    def tearDownClass(cls):
        helpers.cleanup(cls.store, cls.path)

    def test_mendelian_rate_is_low(self):
        self.assertLess(
            self.stats.mendelian_rate, 0.01,
            f"got {self.stats.mendelian_rate:.3%}; a true parent-child pair "
            "should only violate Mendel through genotyping error",
        )

    def test_heterozygous_sites_mostly_resolve(self):
        self.assertGreater(
            self.stats.het_resolution_rate, 0.35,
            "a homozygous mother pins the transmitted allele; that should "
            "resolve roughly half of the child's heterozygous sites",
        )

    def test_phase_is_written(self):
        row = self.store.db.execute(
            "SELECT COUNT(*) FROM phased WHERE kit_id=? AND pat IS NOT NULL",
            (self.child,),
        ).fetchone()
        self.assertGreater(row[0], 1000)

    def test_export_produces_readable_kit(self):
        fd, out = tempfile.mkstemp(suffix=".txt")
        os.close(fd)
        try:
            counts = phase_mod.export_phased_kit(self.store, self.child, "paternal", out)
            self.assertGreater(counts["resolved"], 1000)
            info, records = raw_mod.read(out)
            rows = list(records)
            self.assertGreater(len(rows), 1000)
            for _c, _p, _r, gt in rows[:200]:
                self.assertIn(gt, ("--",) + tuple(a * 2 for a in "ACGTID"),
                              "a phased export is homozygous or missing, never het")
        finally:
            os.unlink(out)


class TestSimulator(unittest.TestCase):
    """The simulator is calibrated against relationships whose average
    sharing is well established from published data."""

    ITER = 300

    def _mean(self, key: str) -> float:
        rel = sim_mod.CATALOGUE[key]
        return sim_mod.simulate(rel, iterations=self.ITER, min_cm=7.0, seed=3).mean

    def test_parent_child_is_the_whole_genome(self):
        mean = self._mean("parent")
        self.assertGreater(mean, 3400)
        self.assertLess(mean, 3700)

    def test_full_siblings(self):
        # Published average 2613 cM.
        self.assertAlmostEqual(self._mean("sibling"), 2613, delta=180)

    def test_second_degree_relationships_agree_with_each_other(self):
        # Half siblings, grandparents and aunt/uncle all sit near 1750 cM.
        # That they land together is the point: total sharing cannot tell
        # them apart, which is what makes this range genealogically hard.
        for key in ("half_sibling", "gparent", "avuncular"):
            with self.subTest(relationship=key):
                self.assertAlmostEqual(self._mean(key), 1750, delta=220)

    def test_first_cousins(self):
        # Published average 866 cM.
        self.assertAlmostEqual(self._mean("1c"), 866, delta=150)

    def test_sharing_falls_by_half_each_cousin_degree(self):
        means = [self._mean(k) for k in ("1c", "2c", "3c")]
        for closer, further in zip(means, means[1:]):
            self.assertGreater(closer, further * 2.0)

    def test_distant_relatives_often_share_nothing(self):
        rel = sim_mod.CATALOGUE["4c"]
        dist = sim_mod.simulate(rel, iterations=self.ITER, min_cm=7.0, seed=5)
        self.assertGreater(
            dist.p_undetected, 0.15,
            "a substantial share of real fourth cousins share no detectable "
            "DNA, which is why a missing match proves nothing at this distance",
        )

    def test_full_siblings_have_fully_identical_regions(self):
        sibs = sim_mod.simulate(sim_mod.CATALOGUE["sibling"], iterations=100, seed=2)
        cousins = sim_mod.simulate(sim_mod.CATALOGUE["1c"], iterations=100, seed=2)
        self.assertGreater(sum(sibs.ibd2) / len(sibs.ibd2), 500)
        self.assertLess(sum(cousins.ibd2) / len(cousins.ibd2), 60,
                        "cousins should almost never be fully identical")


