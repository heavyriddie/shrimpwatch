def _write(text: str, suffix: str = ".txt") -> str:
    fd, path = tempfile.mkstemp(suffix=suffix)
    with os.fdopen(fd, "w") as fh:
        fh.write(text)
    return path


class TestGenome(unittest.TestCase):
    def test_chromosome_normalisation(self):
        self.assertEqual(normalize_chrom("chr7"), "7")
        self.assertEqual(normalize_chrom("23"), "X")
        self.assertEqual(normalize_chrom("24"), "Y")
        self.assertEqual(normalize_chrom("25"), "X", "PAR folds into X")
        self.assertEqual(normalize_chrom("26"), "MT")
        self.assertIsNone(normalize_chrom("99"))

    def test_linear_map_totals(self):
        gmap = GeneticMap.linear("37")
        total = gmap.autosomal_total_cm()
        self.assertGreater(total, 3400)
        self.assertLess(total, 3700)

    def test_map_is_monotone(self):
        gmap = GeneticMap.linear("37")
        a = gmap.cm_at("1", 10_000_000)
        b = gmap.cm_at("1", 100_000_000)
        self.assertLess(a, b)
        self.assertAlmostEqual(gmap.length_cm("1", 100_000_000, 10_000_000), b - a, places=6)

    def test_build_detection(self):
        # A coordinate past the GRCh38 end of chr1 can only be build 37.
        self.assertEqual(detect_build([("1", 249_000_000)]), "37")


class TestRawParsing(unittest.TestCase):
    def test_23andme(self):
        path = _write(TWENTYTHREE)
        try:
            info, records, stats = raw_mod.read_with_stats(path)
            rows = list(records)
            self.assertEqual(info.vendor, "23andMe")
            self.assertEqual(info.build, "37")
            self.assertEqual(len(rows), 6)
            self.assertEqual(rows[0], ("1", 82154, "rs4477212", "AA"))
            self.assertEqual(rows[2][3], "--", "no-calls normalise")
            self.assertEqual(rows[3], ("X", 2699645, "rs28569024", "G"))
            self.assertEqual(stats.called, 5)
        finally:
            os.unlink(path)

    def test_ancestry(self):
        path = _write(ANCESTRY)
        try:
            info, records, _ = raw_mod.read_with_stats(path)
            rows = list(records)
            self.assertEqual(info.vendor, "AncestryDNA")
            self.assertEqual(rows[1][3], "AG", "alleles are sorted, so GA becomes AG")
            self.assertEqual(rows[2][3], "--", "Ancestry writes no-calls as 0")
            self.assertEqual(rows[3][0], "X")
            self.assertEqual(rows[4][0], "MT")
        finally:
            os.unlink(path)

    def test_cross_vendor_agreement(self):
        """The same site read from two vendors must produce the same genotype."""
        p1, p2 = _write(TWENTYTHREE), _write(ANCESTRY)
        try:
            _, r1 = raw_mod.read(p1)
            _, r2 = raw_mod.read(p2)
            a = {(c, p): g for c, p, _, g in r1}
            b = {(c, p): g for c, p, _, g in r2}
            shared = set(a) & set(b)
            self.assertTrue(shared)
            for key in shared:
                if a[key] != "--" and b[key] != "--":
                    self.assertTrue(
                        qc_mod.same_call(a[key], b[key]),
                        f"vendors disagree at {key}: {a[key]} vs {b[key]}",
                    )
            # The X is where the two spellings genuinely differ: one vendor
            # writes a hemizygous call once, the other doubles it, and which
            # is correct depends on a sex the parser has not established yet.
            self.assertEqual(a[("X", 2699645)], "G")
            self.assertEqual(b[("X", 2699645)], "GG")
            self.assertTrue(qc_mod.same_call("G", "GG"))
            self.assertFalse(qc_mod.same_call("AG", "GG"))
        finally:
            os.unlink(p1)
            os.unlink(p2)

    def test_genotype_normalisation(self):
        self.assertEqual(raw_mod.normalize_genotype(["G", "A"]), "AG")
        self.assertEqual(raw_mod.normalize_genotype(["AG"]), "AG")
        self.assertEqual(raw_mod.normalize_genotype(["0", "0"]), "--")
        self.assertEqual(raw_mod.normalize_genotype(["A", "0"]), "--",
                         "a half-called site is unusable")
        self.assertEqual(raw_mod.normalize_genotype(["--"]), "--")


