class TestPrediction(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        fd, cls.path = tempfile.mkstemp(suffix=".db")
        os.close(fd)
        os.unlink(cls.path)
        from roots.store import Store

        cls.store = Store(cls.path)
        cls.gmap = GeneticMap.linear("37")

    @classmethod
    def tearDownClass(cls):
        helpers.cleanup(cls.store, cls.path)

    def _top(self, cm: float, **kw) -> str:
        pred = predict_mod.predict(
            self.store, cm, gmap=self.gmap, iterations=300, **kw
        )
        return pred.candidates[0].rel.key

    def test_parent_level_sharing(self):
        self.assertIn(self._top(3480), ("parent", "twin"))

    def test_sibling_level_sharing(self):
        self.assertEqual(self._top(2600, ibd2_cm=850), "sibling")

    def test_prior_pulls_low_sharing_toward_distant_relatives(self):
        with_prior = self._top(60)
        flat = self._top(60, use_prior=False)
        self.assertNotEqual(
            with_prior, flat,
            "at 60 cM the sheer number of distant relatives should outweigh "
            "the better per-pair fit of a closer relationship",
        )

    def test_fit_rejects_an_impossible_claim(self):
        rel = sim_mod.CATALOGUE["3c"]
        fit = predict_mod.fit_hypothesis(
            self.store, rel, 900.0, gmap=self.gmap, iterations=300
        )
        self.assertFalse(fit.plausible)
        self.assertIn("higher", fit.comment)

    def test_fit_accepts_a_reasonable_claim(self):
        rel = sim_mod.CATALOGUE["1c"]
        fit = predict_mod.fit_hypothesis(
            self.store, rel, 870.0, gmap=self.gmap, iterations=300
        )
        self.assertTrue(fit.plausible)

    def test_relative_counts_grow_with_distance(self):
        counts = [
            predict_mod.expected_relative_count(sim_mod.CATALOGUE[k])
            for k in ("1c", "2c", "3c", "4c")
        ]
        for closer, further in zip(counts, counts[1:]):
            self.assertLess(closer, further)


class TestProjection(unittest.TestCase):
    def test_relationship_projects_onto_a_parent(self):
        from roots.hypothesis import project_to_parent

        # Your paternal first cousin once removed is your father's first cousin.
        rel = sim_mod.CATALOGUE["1c1r"]
        projected = project_to_parent(rel)
        self.assertIsNotNone(projected)
        self.assertEqual(projected.up, rel.up - 1)
        self.assertEqual(projected.down, rel.down)

    def test_your_half_sibling_is_your_parents_child(self):
        from roots.hypothesis import project_to_parent

        rel = sim_mod.CATALOGUE["half_sibling"]
        projected = project_to_parent(rel)
        self.assertEqual(projected.up, 0)
        self.assertEqual(projected.name, "parent/child")


